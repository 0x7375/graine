export const LanguageContext = createContext<Language>("en");
export function useLanguage() { return useContext(LanguageContext); }
export function translate(language: Language, key: string) {
  return language === "fr" ? (french[key] ?? key) : key;
}
/** Localize a counted noun without embedding “(s)” in UI copy. */
export function countLabel(language: Language, count: number, singular: string, plural: string): string {
  const form = count !== 0 && new Intl.PluralRules(language).select(count) === "one" ? singular : plural;
  return `${count} ${translate(language, form)}`;
}

export function initialLanguage(): Language {
  return navigator.language.toLowerCase().startsWith("fr") ? "fr" : "en";
}
