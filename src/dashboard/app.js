
const DATA = window.GRAINE_DATA;

const $ = (id) => document.getElementById(id);

const esc = (value) =>
  String(value ?? '').replace(/[&<>"']/g, (character) => ({
    '&': '&amp;',
    '<': '&lt;',
    '>': '&gt;',
    '"': '&quot;',
    "'": '&#39;',
  })[character]);

const fmt = (number) => {
  if (number === null || number === undefined) {
    return '—';
  }

  const value = Number(number);
  const absolute = Math.abs(value);
  const sign = value < 0 ? '−' : '';

  if (absolute >= 1024 ** 4) {
    return sign + (absolute / 1024 ** 4).toFixed(2) + ' TiB';
  }

  if (absolute >= 1024 ** 3) {
    return sign + (absolute / 1024 ** 3).toFixed(2) + ' GiB';
  }

  if (absolute >= 1024 ** 2) {
    return sign + (absolute / 1024 ** 2).toFixed(1) + ' MiB';
  }

  if (absolute >= 1024) {
    return sign + (absolute / 1024).toFixed(1) + ' KiB';
  }

  return sign + absolute.toFixed(0) + ' B';
};

const net = (torrent) =>
  (torrent.uploaded_bytes || 0) - (torrent.downloaded_bytes || 0);

const fmtNet = (bytes) => `
    <span class="${bytes >= 0 ? 'positive' : 'negative'}">
        ${bytes >= 0 ? '+' : '−'}${fmt(Math.abs(bytes))}
    </span>
`;

const date = (timestamp) =>
  timestamp ? new Date(timestamp * 1000).toLocaleString() : '—';

const pct = (number) =>
  `${Number(number || 0).toFixed(1)}%`;

const period = (name) =>
  DATA.periods[name] || { trackers: [], torrents: [] };


// --------------------------------------------------
// Header
// --------------------------------------------------

function renderHeader() {
  const run = DATA.run;
  const mode = run.mode === 'dry' ? 'DRY RUN' : 'LIVE';

  $('runstate').innerHTML = `
        <span class="dot ${run.mode === 'dry' ? 'dry' : ''}"></span>
        <span>${mode} · ${esc(run.result.replace('_', ' '))}</span>
    `;

  $('last-run').textContent = `
        Last execution ${date(run.timestamp)}
        · ${run.managed_torrents} managed torrents
        · ${run.clusters} completed clusters
    `.trim();

  if (run.mode === 'dry') {
    $('notice').innerHTML = `
            <div class="notice">
                This page was generated by a dry run. Deletion candidates are
                previews; no torrents were removed and no eviction events
                were recorded.
            </div>
        `;
  } else if (run.result === 'over_limit') {
    $('notice').innerHTML = `
            <div class="notice">
                Disk remains above the high watermark: Graine could not reclaim
                enough space without evicting protected or grace-period data.
            </div>
        `;
  } else {
    $('notice').innerHTML = '';
  }
}


// --------------------------------------------------
// Overview metrics
// --------------------------------------------------

function renderMetrics() {
  const run = DATA.run;
  const actual = run.actual_reclaimed_bytes;

  const cards = [
    [
      'Disk used',
      pct(run.disk_used_percent),
      `${fmt(run.disk_used_bytes)} of ${fmt(run.disk_total_bytes)}`,
    ],
    [
      'Reclaimable',
      fmt(DATA.reclaimable_bytes),
      'Retained completed torrent data',
    ],
    [
      'Protected',
      fmt(DATA.protected_bytes),
      'Shared with library / external hardlinks',
    ],
    [
      run.mode === 'dry' ? 'Would reclaim' : 'Reclaimed this run',
      actual === null
        ? fmt(run.estimated_reclaimed_bytes)
        : fmt(actual),
      actual === null
        ? 'Estimated from this run’s candidates'
        : 'Observed df usage change',
    ],
  ];

  $('metrics').innerHTML = cards
    .map((card, index) => `
            <div class="card metric">
                <div class="label">${card[0]}</div>
                <div class="value ${index === 3 && Number(actual || 0) > 0 ? 'good' : ''
      }">${card[1]}</div>
                <div class="hint">${card[2]}</div>
            </div>
        `)
    .join('');
}


// --------------------------------------------------
// Disk usage chart
// --------------------------------------------------

function renderChart() {
  const history = DATA.history || [];

  if (!history.length) {
    $('disk-chart').innerHTML = `
            <div class="empty">No history yet.</div>
        `;
    return;
  }

  const width = 900;
  const height = 230;

  const left = 48;
  const right = 18;
  const top = 14;
  const bottom = 30;

  const innerWidth = width - left - right;
  const innerHeight = height - top - bottom;

  const values = history.map((entry) =>
    Number(entry.disk_used_percent || 0)
  );

  const max = Math.max(
    100,
    ...values,
    Number(history[history.length - 1].high_watermark_percent || 85)
  );

  const min = 0;

  const x = (index) =>
    left + (
      history.length === 1
        ? innerWidth / 2
        : index / (history.length - 1) * innerWidth
    );

  const y = (value) =>
    top + (max - value) / (max - min) * innerHeight;

  let svg = `
        <svg
            class="chart"
            viewBox="0 0 ${width} ${height}"
            role="img"
            aria-label="Disk usage history"
        >
    `;

  // Horizontal grid lines and labels.
  for (let value = 0; value <= 100; value += 20) {
    svg += `
            <line
                class="gridline"
                x1="${left}"
                x2="${width - right}"
                y1="${y(value)}"
                y2="${y(value)}"
            />
            <text
                x="${left - 9}"
                y="${y(value) + 4}"
                text-anchor="end"
            >${value}%</text>
        `;
  }

  const lastEntry = history[history.length - 1];

  const high = Number(lastEntry.high_watermark_percent || 85);
  const low = Number(lastEntry.low_watermark_percent || 80);

  // Watermark reference lines.
  svg += `
        <line
            class="high"
            x1="${left}"
            x2="${width - right}"
            y1="${y(high)}"
            y2="${y(high)}"
        />
        <line
            class="low"
            x1="${left}"
            x2="${width - right}"
            y1="${y(low)}"
            y2="${y(low)}"
        />
    `;

  // Usage history line.
  const points = history
    .map((entry, index) =>
      `${x(index)},${y(entry.disk_used_percent)}`
    )
    .join(' ');

  svg += `
        <polyline class="usage" points="${points}" />
    `;

  // Highlight the latest measurement.
  svg += `
        <circle
            cx="${x(history.length - 1)}"
            cy="${y(lastEntry.disk_used_percent)}"
            r="4"
            fill="var(--green)"
        />

        <text x="${left}" y="${height - 7}">
            ${esc(new Date(history[0].timestamp * 1000).toLocaleDateString())}
        </text>

        <text
            x="${width - right}"
            y="${height - 7}"
            text-anchor="end"
        >
            ${esc(new Date(lastEntry.timestamp * 1000).toLocaleDateString())}
        </text>
    `;

  svg += '</svg>';

  $('disk-chart').innerHTML = svg;
}


// --------------------------------------------------
// Reclaimable vs protected space
// --------------------------------------------------

function renderSplit() {
  const reclaimable = Number(DATA.reclaimable_bytes || 0);
  const protectedBytes = Number(DATA.protected_bytes || 0);

  const total = reclaimable + protectedBytes;
  const reclaimablePercent = total
    ? 100 * reclaimable / total
    : 0;

  $('space-split').innerHTML = `
        <div style="
            font-size: 25px;
            font-weight: 650;
            letter-spacing: -.04em;
        ">
            ${fmt(total)}
        </div>

        <div
            class="bar"
            style="height: 16px; margin: 12px 0"
        >
            <div
                class="used"
                style="width: ${reclaimablePercent}%"
            ></div>

            <div
                class="protected"
                style="width: ${100 - reclaimablePercent}%"
            ></div>
        </div>

        <div class="splitlabels">
            <span>
                ${fmt(reclaimable)} reclaimable
                · ${reclaimablePercent.toFixed(1)}%
            </span>

            <span>
                ${fmt(protectedBytes)} protected
                · ${(100 - reclaimablePercent).toFixed(1)}%
            </span>
        </div>
    `;
}


// --------------------------------------------------
// Pool usage
// --------------------------------------------------

function renderPools() {
  const pools = DATA.pools || [];

  if (!pools.length) {
    $('pool-list').innerHTML = `
            <div class="empty">No pools.</div>
        `;
    return;
  }

  $('pool-list').innerHTML = pools
    .map((pool) => {
      const used = Number(pool.reclaimable_bytes || 0);

      const capacity = pool.capacity_bytes === null
        ? null
        : Number(pool.capacity_bytes);

      const ratio = capacity
        ? Math.min(100, used / capacity * 100)
        : 0;

      return `
                <div class="pool">
                    <div class="pooltop">
                        <strong>${esc(pool.name)}</strong>

                        <span>
                            ${fmt(used)} /
                            ${capacity ? fmt(capacity) : 'No cap'}
                            reclaimable
                        </span>
                    </div>

                    <div class="bar">
                        <div
                            class="used"
                            style="width: ${capacity ? ratio : 0}%"
                        ></div>
                    </div>

                    <div class="splitlabels">
                        <span>
                            ${fmt(pool.protected_bytes)} protected
                        </span>

                        <span>
                            ${capacity
          ? ratio.toFixed(1) + '% of cap'
          : 'Capacity unlimited'
        }
                        </span>
                    </div>
                </div>
            `;
    })
    .join('');
}


// --------------------------------------------------
// Tracker performance
// --------------------------------------------------

function renderTrackers() {
  const selectedPeriod = period($('tracker-period').value);
  const rows = selectedPeriod.trackers || [];

  if (!rows.length) {
    $('tracker-table').innerHTML = `
            <div class="empty">
                No tracker activity recorded for this period yet.
            </div>
        `;
    return;
  }

  const measures = ['Uploaded', 'Downloaded', 'Net'];

  const groups = ['Total', 'Regular', 'Cross-seed']
    .map((label) => `
            <th class="num" colspan="3">${label}</th>
        `)
    .join('');

  const subHeaders = Array(3)
    .fill(
      measures
        .map((measure) => `
                    <th class="num">${measure}</th>
                `)
        .join('')
    )
    .join('');

  const header = `
        <thead>
            <tr>
                <th rowspan="2">Tracker</th>
                ${groups}
            </tr>

            <tr>
                ${subHeaders}
            </tr>
        </thead>
    `;

  const body = rows
    .map((tracker) => {
      const cells = [
        tracker.total,
        tracker.regular,
        tracker.cross_seed,
      ]
        .map((values) => `
                    <td class="num">${fmt(values.uploaded_bytes)}</td>
                    <td class="num">${fmt(values.downloaded_bytes)}</td>
                    <td class="num">${fmtNet(net(values))}</td>
                `)
        .join('');

      return `
                <tr>
                    <td>${esc(tracker.tracker)}</td>
                    ${cells}
                </tr>
            `;
    })
    .join('');

  $('tracker-table').innerHTML = `
        <table>
            ${header}
            <tbody>${body}</tbody>
        </table>
    `;
}


// --------------------------------------------------
// Torrent leaderboard
// --------------------------------------------------

function ratio(torrent) {
  if (torrent.downloaded_bytes > 0) {
    return torrent.uploaded_bytes / torrent.downloaded_bytes;
  }

  return torrent.uploaded_bytes > 0 ? Infinity : 0;
}

function renderLeaderboard() {
  const selectedPeriod = period($('leader-period').value);
  const metric = $('leader-metric').value;

  const rows = [...(selectedPeriod.torrents || [])]
    .sort((a, b) => {
      const valueA = metric === 'net'
        ? net(a)
        : metric === 'ratio'
          ? ratio(a)
          : a.uploaded_bytes;

      const valueB = metric === 'net'
        ? net(b)
        : metric === 'ratio'
          ? ratio(b)
          : b.uploaded_bytes;

      return valueB - valueA;
    })
    .slice(0, 100);

  if (!rows.length) {
    $('leader-table').innerHTML = `
            <div class="empty">
                No torrent activity recorded for this period yet.
            </div>
        `;
    return;
  }

  const body = rows
    .map((torrent, index) => {
      const torrentRatio = ratio(torrent);

      const rankValue = metric === 'net'
        ? fmtNet(net(torrent))
        : metric === 'ratio'
          ? (
            Number.isFinite(torrentRatio)
              ? torrentRatio.toFixed(2) + '×'
              : '∞'
          )
          : fmt(torrent.uploaded_bytes);

      return `
                <tr>
                    <td class="rank">${index + 1}</td>

                    <td
                        class="namecell"
                        title="${esc(torrent.name)}"
                    >
                        ${esc(torrent.name)}

                        <small>
                            ${esc(torrent.tracker)}
                            ·
                            ${torrent.is_cross_seed ? 'Cross-seed' : 'Regular'}
                        </small>
                    </td>

                    <td class="num">${rankValue}</td>
                    <td class="num">${fmt(torrent.uploaded_bytes)}</td>
                    <td class="num">${fmt(torrent.downloaded_bytes)}</td>
                    <td class="num">${fmtNet(net(torrent))}</td>

                    <td class="num">
                        ${Number.isFinite(torrentRatio)
          ? torrentRatio.toFixed(2) + '×'
          : '∞'
        }
                    </td>
                </tr>
            `;
    })
    .join('');

  $('leader-table').innerHTML = `
        <table>
            <thead>
                <tr>
                    <th>#</th>
                    <th>Torrent</th>
                    <th class="num">Rank value</th>
                    <th class="num">Uploaded</th>
                    <th class="num">Downloaded</th>
                    <th class="num">Net</th>
                    <th class="num">Ratio</th>
                </tr>
            </thead>

            <tbody>${body}</tbody>
        </table>
    `;
}


// --------------------------------------------------
// Ranking
// --------------------------------------------------

function badge(status) {
  const className =
    status === 'GOOD' || status === 'FREE'
      ? 'good'
      : status === 'GRACE' || status === 'WOULD DELETE'
        ? 'warn'
        : status === 'DELETED'
          ? 'bad'
          : '';

  return `
        <span class="badge ${className}">
            ${esc(status)}
        </span>
    `;
}

function renderRanking() {
  const query = $('ranking-search').value.toLowerCase();
  const filter = $('ranking-status').value;

  const rows = (DATA.ranking || []).filter((cluster) => {
    const matchesStatus =
      filter === 'all' || cluster.status === filter;

    const searchableText = [
      cluster.name,
      cluster.pool,
      cluster.tracker_hosts.join(' '),
      cluster.torrent_names.join(' '),
    ]
      .join(' ')
      .toLowerCase();

    return matchesStatus && searchableText.includes(query);
  });

  if (!rows.length) {
    $('ranking-table').innerHTML = `
            <div class="empty">No matching clusters.</div>
        `;
    return;
  }

  const body = rows
    .map((cluster) => `
            <tr>
                <td class="rank">${cluster.rank}</td>

                <td
                    class="namecell"
                    title="${esc(cluster.torrent_names.join('\n'))}"
                >
                    ${esc(cluster.name)}

                    <small>
                        ${cluster.torrent_count} torrent(s)
                        · ${esc(cluster.tracker_hosts.join(', '))}
                    </small>
                </td>

                <td>${esc(cluster.pool)}</td>

                <td>
                    ${badge(cluster.status)}

                    ${cluster.reason
        ? `<div class="tiny">${esc(cluster.reason)}</div>`
        : ''
      }
                </td>

                <td class="num">${cluster.priority}</td>

                <td class="num">
                    ${cluster.score === null
        ? '—'
        : Number(cluster.score).toFixed(2)
      }
                </td>

                <td class="num">${fmt(cluster.data_bytes)}</td>
                <td class="num">${fmt(cluster.cost_bytes)}</td>
                <td class="num">${fmt(cluster.uploaded_bytes)}</td>
            </tr>
        `)
    .join('');

  $('ranking-table').innerHTML = `
        <table>
            <thead>
                <tr>
                    <th>#</th>
                    <th>Cluster / torrents</th>
                    <th>Pool</th>
                    <th>Decision</th>
                    <th class="num">Priority</th>
                    <th class="num">Score</th>
                    <th class="num">Data</th>
                    <th class="num">Cost</th>
                    <th class="num">Uploaded</th>
                </tr>
            </thead>

            <tbody>${body}</tbody>
        </table>
    `;
}


// --------------------------------------------------
// Eviction history
// --------------------------------------------------

function renderDeletions() {
  const batches = [...(DATA.deletions || [])]
    .sort((a, b) => b.timestamp - a.timestamp);

  if (!batches.length) {
    $('deletion-table').innerHTML = `
            <div class="empty">
                No actual eviction has been recorded yet.
            </div>
        `;
    return;
  }

  const rows = [];

  for (const batch of batches) {
    for (let index = 0; index < batch.clusters.length; index++) {
      const cluster = batch.clusters[index];

      rows.push(`
                <tr>
                    <td>${date(batch.timestamp)}</td>

                    <td
                        class="namecell"
                        title="${esc(cluster.torrent_names.join('\n'))}"
                    >
                        ${esc(cluster.name)}

                        <small>
                            ${esc(cluster.tracker_hosts.join(', '))}
                        </small>
                    </td>

                    <td>${esc(cluster.pool)}</td>
                    <td>${esc(cluster.reason)}</td>

                    <td class="num">
                        ${cluster.score === null
          ? '—'
          : Number(cluster.score).toFixed(2)
        }
                    </td>

                    <td class="num">
                        ${fmt(cluster.estimated_reclaimed_bytes)}
                    </td>

                    <td class="num">
                        ${index === 0 && batch.observed_reclaimed_bytes !== null
          ? fmt(batch.observed_reclaimed_bytes)
          : '—'
        }
                    </td>
                </tr>
            `);
    }
  }

  $('deletion-table').innerHTML = `
        <table>
            <thead>
                <tr>
                    <th>When</th>
                    <th>Cluster</th>
                    <th>Pool</th>
                    <th>Reason</th>
                    <th class="num">Score</th>
                    <th class="num">Estimated</th>
                    <th class="num">Observed batch</th>
                </tr>
            </thead>

            <tbody>${rows.join('')}</tbody>
        </table>
    `;
}


